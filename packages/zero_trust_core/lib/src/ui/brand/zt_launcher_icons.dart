import 'dart:convert';
import 'dart:io';
import 'dart:ui' as ui;
import 'dart:typed_data';

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';

import '../../config/zt_suite.dart';
import '../theme/zt_theme.dart';

/// Draws an app's launcher icons (Android, iOS and web) from the suite's
/// brand mark ([ZtBrandMark]), so the icon on the home screen is the same
/// mark the app shows on sign-in and in "Other Zero-Trust apps".
///
/// Run from an app's `tool/launcher_icon_test.dart` with `flutter test`
/// (it needs the engine to draw), from the app's root folder:
///
/// ```dart
/// void main() => testWidgets('launcher icons', (tester) =>
///     tester.runAsync(() => ZtLauncherIcons.write(ZtSuite.notes)));
/// ```
abstract final class ZtLauncherIcons {
  static const Map<String, double> _densities = <String, double>{
    'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4, //
  };

  /// Writes every launcher icon for [app] under [root] (the app's folder).
  static Future<void> write(ZtSuiteApp app, {String root = '.'}) async {
    await _loadIconFont();
    await _android(app, '$root/android/app/src/main/res');
    await _ios(app, '$root/ios/Runner/Assets.xcassets/AppIcon.appiconset');
    await _web(app, '$root/web');
  }

  static Color _end(ZtSuiteApp app) =>
      Color.lerp(ZtTheme.brandSeed, app.accent, 0.75)!;

  static Future<void> _android(ZtSuiteApp app, String res) async {
    if (!Directory(res).existsSync()) return;
    for (final d in _densities.entries) {
      Directory('$res/mipmap-${d.key}').createSync(recursive: true);
      // Older launchers: the whole rounded mark, 48dp.
      await _png('$res/mipmap-${d.key}/ic_launcher.png', (48 * d.value).round(),
          (c, s) => _mark(c, s, app, radius: 0.28));
      // Adaptive icons: the symbol alone on 108dp, half of the 72dp that
      // shows, like on the mark. Also used as the themed (monochrome) icon.
      await _png('$res/mipmap-${d.key}/ic_launcher_foreground.png',
          (108 * d.value).round(), (c, s) => _symbol(c, s, app, s / 3));
      // Earlier generators wrote the background as a bitmap.
      final old = File('$res/mipmap-${d.key}/ic_launcher_background.png');
      if (old.existsSync()) old.deleteSync();
    }
    Directory('$res/drawable').createSync(recursive: true);
    File('$res/drawable/ic_launcher_background.xml').writeAsStringSync('''
<?xml version="1.0" encoding="utf-8"?>
<!-- The brand mark's gradient. Generated by ZtLauncherIcons (zero_trust_core). -->
<shape xmlns:android="http://schemas.android.com/apk/res/android">
    <gradient
        android:angle="315"
        android:startColor="${_hex(ZtTheme.brandSeed)}"
        android:endColor="${_hex(_end(app))}" />
</shape>
''');
    Directory('$res/mipmap-anydpi-v26').createSync(recursive: true);
    File('$res/mipmap-anydpi-v26/ic_launcher.xml').writeAsStringSync('''
<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
''');
  }

  /// iOS rounds the corners itself and wants no transparency.
  static Future<void> _ios(ZtSuiteApp app, String dir) async {
    final contents = File('$dir/Contents.json');
    if (!contents.existsSync()) return;
    final json = jsonDecode(contents.readAsStringSync()) as Map;
    for (final image in (json['images'] as List).cast<Map>()) {
      final name = image['filename'] as String?;
      if (name == null) continue;
      final pt = double.parse((image['size'] as String).split('x').first);
      // Xcode's single-size catalog leaves out the scale (1x).
      final scale = double.parse(
          ((image['scale'] as String?) ?? '1x').replaceAll('x', ''));
      await _png(
          '$dir/$name',
          (pt * scale).round(),
          opaque: true,
          (c, s) => _mark(c, s, app, radius: 0));
    }
  }

  static Future<void> _web(ZtSuiteApp app, String web) async {
    if (!Directory(web).existsSync()) return;
    await _png(
        '$web/favicon.png', 16, (c, s) => _mark(c, s, app, radius: 0.28));
    for (final size in [192, 512]) {
      await _png('$web/icons/Icon-$size.png', size,
          (c, s) => _mark(c, s, app, radius: 0.28));
      // Maskable: full bleed, symbol inside the 80% safe circle.
      await _png('$web/icons/Icon-maskable-$size.png', size,
          (c, s) => _mark(c, s, app, radius: 0, symbol: 0.4));
    }
  }

  static void _mark(Canvas canvas, double size, ZtSuiteApp app,
      {required double radius, double symbol = 0.5}) {
    final rect = Offset.zero & Size(size, size);
    canvas.drawRRect(
      RRect.fromRectAndRadius(rect, Radius.circular(size * radius)),
      Paint()
        ..isAntiAlias = true
        ..shader = LinearGradient(
          begin: Alignment.topLeft,
          end: Alignment.bottomRight,
          colors: [ZtTheme.brandSeed, _end(app)],
        ).createShader(rect),
    );
    _symbol(canvas, size, app, size * symbol);
  }

  static void _symbol(
      Canvas canvas, double size, ZtSuiteApp app, double symbolSize) {
    final icon = app.icon;
    final text = TextPainter(
      textDirection: TextDirection.ltr,
      text: TextSpan(
        text: String.fromCharCode(icon.codePoint),
        style: TextStyle(
          fontFamily: icon.fontFamily,
          package: icon.fontPackage,
          fontSize: symbolSize,
          height: 1,
          color: Colors.white,
        ),
      ),
    )..layout();
    text.paint(
        canvas, Offset((size - text.width) / 2, (size - text.height) / 2));
  }

  /// [opaque] writes RGB without an alpha channel: App Store validation
  /// rejects iOS icons that have one, even when it's fully opaque.
  static Future<void> _png(
      String path, int size, void Function(Canvas canvas, double size) paint,
      {bool opaque = false}) async {
    final recorder = ui.PictureRecorder();
    paint(Canvas(recorder), size.toDouble());
    final image = await recorder.endRecording().toImage(size, size);
    if (!opaque) {
      final data = await image.toByteData(format: ui.ImageByteFormat.png);
      File(path).writeAsBytesSync(data!.buffer.asUint8List());
      return;
    }
    final rgba = (await image.toByteData(format: ui.ImageByteFormat.rawRgba))!
        .buffer
        .asUint8List();
    File(path).writeAsBytesSync(_encodeRgbPng(rgba, size));
  }

  /// A minimal PNG encoder for an opaque RGB image (colour type 2).
  static Uint8List _encodeRgbPng(Uint8List rgba, int size) {
    final raw = BytesBuilder();
    for (var y = 0; y < size; y++) {
      raw.addByte(0); // filter: none
      for (var x = 0; x < size; x++) {
        final i = (y * size + x) * 4;
        raw.add([rgba[i], rgba[i + 1], rgba[i + 2]]);
      }
    }
    final out = BytesBuilder()
      ..add([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);
    void chunk(String type, List<int> data) {
      final body = [...ascii.encode(type), ...data];
      out
        ..add(_u32(data.length))
        ..add(body)
        ..add(_u32(_crc32(body)));
    }

    chunk('IHDR', [..._u32(size), ..._u32(size), 8, 2, 0, 0, 0]);
    chunk('IDAT', ZLibCodec(level: 9).encode(raw.takeBytes()));
    chunk('IEND', const []);
    return out.takeBytes();
  }

  static List<int> _u32(int v) =>
      [(v >> 24) & 0xFF, (v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF];

  static int _crc32(List<int> bytes) {
    var crc = 0xFFFFFFFF;
    for (final b in bytes) {
      crc ^= b;
      for (var k = 0; k < 8; k++) {
        crc = (crc & 1) != 0 ? (crc >> 1) ^ 0xEDB88320 : crc >> 1;
      }
    }
    return crc ^ 0xFFFFFFFF;
  }

  /// Tests draw with a blank font unless the real icon font is loaded.
  static Future<void> _loadIconFont() async {
    final root = Platform.environment['FLUTTER_ROOT'];
    final file = File(
        '$root/bin/cache/artifacts/material_fonts/MaterialIcons-Regular.otf');
    if (root == null || !file.existsSync()) {
      throw StateError('Run with `flutter test` so FLUTTER_ROOT is set.');
    }
    final loader = FontLoader('MaterialIcons')
      ..addFont(file.readAsBytes().then(ByteData.sublistView));
    await loader.load();
  }

  static String _hex(Color c) =>
      '#${(c.toARGB32() & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';
}
